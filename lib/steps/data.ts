export function listApplicationSteps(query?: string, category?: string): ApplicationStep[] {
  let items = [...applicationSteps];

  if (category && category !== "all") {
    items = items.filter((item) => item.category === category);
  }

  if (query && query.trim()) {
    const q = query.trim().toLocaleLowerCase("th-TH");
    items = items.filter((item) =>
      `${item.title} ${item.description} ${item.actionSummary} ${item.requiredDocsSummary} ${item.detailedDescription}`
        .toLocaleLowerCase("th-TH")
        .includes(q)
    );
  }

  return items;
}

export function getApplicationStep(id: string): ApplicationStep | null {
  return applicationSteps.find((item) => item.id === id) ?? null;
}
